#!/usr/bin/env python3
"""Write-side CLI for the per-file known-issues registry.

Layout: docs/known-issues/KI-NNN.md (frontmatter + Markdown body) plus a
generated docs/known-issues/README.md index. Agents read the index and single
issue files directly; every write goes through this script so the index never
drifts from the issue files.

Commands:
  new      --title T --severity critical|medium|low --location PATH[,PATH] [--detected YYYY-MM]
  resolve  KI-NNN --ref COMMIT_OR_PR [--note TEXT]
  index    [--check]
  migrate  [--from docs/known-issues.md]

Common options (after the command): --root (repository root, default .),
--dir (registry directory, default docs/known-issues).
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path

DEFAULT_DIR = "docs/known-issues"
DEFAULT_LEGACY = "docs/known-issues.md"
LEGACY_FILES = ("docs/known-issues.md", "docs/archive/known-issues.md")
ARCHIVE_TARGET = "docs/archive/known-issues.md"
INDEX_NAME = "README.md"
INDEX_MARKER = "<!-- generated by ki.py index; do not edit -->"
CLI_HINT = "python3 .agents/skills/docs-policy/scripts/ki.py"

FIELDS = ("id", "title", "severity", "status", "location", "detected", "resolved_ref")
REQUIRED = ("id", "title", "severity", "status")
SEVERITIES = ("critical", "medium", "low")
STATUSES = ("open", "resolved")
SEVERITY_EMOJI = {"critical": "\U0001F534", "medium": "\U0001F7E1", "low": "\U0001F7E2"}
EMOJI_SEVERITY = {emoji: severity for severity, emoji in SEVERITY_EMOJI.items()}

ID_RE = re.compile(r"^KI-(\d+)$")
ISSUE_FILE_RE = re.compile(r"^KI-\d+\.md$")
DETECTED_RE = re.compile(r"^\d{4}-\d{2}$")
LEGACY_HEADING_RE = re.compile(r"^#{2,6}\s+KI-(\d+)\b\s*(.*)$")
H2_RE = re.compile(r"^##\s+(.*)$")
FIELD_RE = re.compile(r"^[-*]\s+\*\*(.+?)\*\*\s*:?\s*(?:[\u2014\u2013-]+\s+)?(.*)$")
RESOLVED_SEPARATOR_RE = re.compile(r"\s(?:[\u2014\u2013]|--|-)(?:\s+|$)")
LINK_RE = re.compile(r"(\]\(\s*<?)([^)\s>]+)")
SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]*:")
MONTHS = {m: i for i, m in enumerate(
    ["january", "february", "march", "april", "may", "june", "july",
     "august", "september", "october", "november", "december"], start=1)}
MONTH_YEAR_RE = re.compile(r"\b(" + "|".join(MONTHS) + r")\s+(\d{4})\b", re.IGNORECASE)
YAML_SPECIAL_START = tuple("[]{}&*#?|-<>=!%@`'\"")

TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "known-issue.template.md"


class KiError(Exception):
    pass


# ------------------------------------------------------------- frontmatter

def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def _quote(value: str) -> str:
    if not value:
        return ""
    needs_quotes = (
        value.startswith(YAML_SPECIAL_START)
        or ": " in value
        or " #" in value
        or value.endswith(":")
        or value != value.strip()
    )
    if needs_quotes:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def parse_frontmatter(text: str) -> tuple[dict[str, str], str, list[str]]:
    """Return (meta, body, errors). Only flat `key: value` pairs are supported."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return {}, text, ["missing frontmatter (file must start with '---')"]
    meta: dict[str, str] = {}
    errors: list[str] = []
    for number in range(1, len(lines)):
        line = lines[number].rstrip("\r\n")
        if line.strip() == "---":
            return meta, "".join(lines[number + 1:]), errors
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            errors.append(f"frontmatter line {number + 1}: expected 'key: value'")
            continue
        meta[key.strip()] = _unquote(value.strip())
    return meta, "", errors + ["unterminated frontmatter (missing closing '---')"]


def render_frontmatter(meta: dict[str, str]) -> str:
    keys = [k for k in FIELDS if k in meta] + [k for k in meta if k not in FIELDS]
    lines = []
    for key in keys:
        value = _quote(meta[key])
        lines.append(f"{key}: {value}" if value else f"{key}:")
    return "---\n" + "\n".join(lines) + "\n---\n"


# ------------------------------------------------------------------ model

@dataclass
class Issue:
    path: Path
    meta: dict[str, str]
    body: str
    parse_errors: list[str]

    @property
    def id(self) -> str:
        return self.meta.get("id", "")

    @property
    def number(self) -> int:
        match = ID_RE.match(self.id) or ID_RE.match(self.path.stem)
        return int(match.group(1)) if match else -1

    @property
    def status(self) -> str:
        return self.meta.get("status", "")

    def text(self) -> str:
        body = self.body.strip("\n")
        return render_frontmatter(self.meta) + ("\n" + body + "\n" if body else "")

    def save(self) -> None:
        self.path.write_text(self.text(), encoding="utf-8")


def load_issue(path: Path) -> Issue:
    meta, body, errors = parse_frontmatter(path.read_text(encoding="utf-8", errors="replace"))
    return Issue(path, meta, body, errors)


def validate_issue(issue: Issue) -> list[str]:
    """Problems that make an issue file invalid (used by doc_check.py)."""
    problems = list(issue.parse_errors)
    for key in REQUIRED:
        if not issue.meta.get(key):
            problems.append(f"missing required field '{key}'")
    if issue.id and not ID_RE.match(issue.id):
        problems.append(f"id '{issue.id}' does not match KI-NNN")
    if issue.id and issue.id != issue.path.stem:
        problems.append(f"id '{issue.id}' does not match file name '{issue.path.name}'")
    severity = issue.meta.get("severity")
    if severity and severity not in SEVERITIES:
        problems.append(f"severity '{severity}' is not one of {', '.join(SEVERITIES)}")
    if issue.status and issue.status not in STATUSES:
        problems.append(f"status '{issue.status}' is not one of {', '.join(STATUSES)}")
    if issue.status == "resolved" and not issue.meta.get("resolved_ref"):
        problems.append("status is resolved but 'resolved_ref' is empty")
    detected = issue.meta.get("detected")
    if detected and not DETECTED_RE.match(detected):
        problems.append(f"detected '{detected}' is not YYYY-MM")
    return problems


def load_issues(directory: Path) -> list[Issue]:
    if not directory.is_dir():
        return []
    issues = [load_issue(p) for p in directory.iterdir() if p.is_file() and ISSUE_FILE_RE.match(p.name)]
    return sorted(issues, key=lambda i: i.number)


# ------------------------------------------------------------------ index

def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _locations(value: str) -> str:
    items = [item.strip().strip("`").strip() for item in value.split(",")]
    items = [item for item in items if item]
    return ", ".join(f"`{item}`" for item in items) if items else "-"


def render_index(issues: list[Issue]) -> str:
    rank = {severity: n for n, severity in enumerate(SEVERITIES)}
    open_issues = sorted(
        (i for i in issues if i.status != "resolved"),
        key=lambda i: (rank.get(i.meta.get("severity", ""), len(rank)), -i.number),
    )
    resolved = sorted((i for i in issues if i.status == "resolved"), key=lambda i: -i.number)

    out = [
        INDEX_MARKER,
        "# Known Issues & Technical Debt",
        "",
        "Registry of inconsistencies, deprecations and follow-ups. One file per",
        "issue (`KI-<nnn>.md`); this index is generated from their frontmatter.",
        "Read the **Open** table and open an issue file only when it affects the",
        "code you are changing. Other documents link issues by id only.",
        "",
        "Write through the CLI, never by editing this file:",
        "",
        "```bash",
        f'{CLI_HINT} new --title "..." --severity medium --location path/to/file',
        f"{CLI_HINT} resolve KI-NNN --ref <commit or PR>",
        f"{CLI_HINT} index   # after editing an issue file by hand",
        "```",
        "",
        "**Severity**: "
        + " \u00b7 ".join(f"{SEVERITY_EMOJI[s]} {s}" for s in SEVERITIES),
        "",
        f"## Open ({len(open_issues)})",
        "",
    ]
    if open_issues:
        out += ["| Id | Severity | Title | Location |", "|---|---|---|---|"]
        for issue in open_issues:
            emoji = SEVERITY_EMOJI.get(issue.meta.get("severity", ""), "?")
            out.append(
                f"| [{issue.id}]({issue.path.name}) | {emoji} | {_cell(issue.meta.get('title', ''))} "
                f"| {_locations(issue.meta.get('location', ''))} |"
            )
    else:
        out.append("_None._")
    out += ["", f"## Resolved ({len(resolved)})", ""]
    if resolved:
        out += ["| Id | Title | Resolved |", "|---|---|---|"]
        for issue in resolved:
            out.append(
                f"| [{issue.id}]({issue.path.name}) | {_cell(issue.meta.get('title', ''))} "
                f"| {_cell(issue.meta.get('resolved_ref', ''))} |"
            )
    else:
        out.append("_None._")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------- registry

class Registry:
    def __init__(self, root: Path, directory: str) -> None:
        self.root = root.resolve()
        self.dir = self.root / directory

    @property
    def index_path(self) -> Path:
        return self.dir / INDEX_NAME

    def issues(self) -> list[Issue]:
        return load_issues(self.dir)

    def get(self, issue_id: str) -> Issue:
        path = self.dir / f"{issue_id}.md"
        if not path.is_file():
            raise KiError(f"{issue_id} not found in {self.rel(self.dir)}")
        return load_issue(path)

    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.root).as_posix()
        except ValueError:
            return str(path)

    def used_numbers(self) -> set[int]:
        numbers = {i.number for i in self.issues() if i.number >= 0}
        for legacy in LEGACY_FILES:
            path = self.root / legacy
            if path.is_file():
                for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
                    match = LEGACY_HEADING_RE.match(line)
                    if match:
                        numbers.add(int(match.group(1)))
        return numbers

    def next_id(self) -> str:
        return f"KI-{max(self.used_numbers(), default=0) + 1:03d}"

    def index_text(self) -> str:
        return render_index(self.issues())

    def index_is_current(self) -> bool:
        return self.index_path.is_file() and self.index_path.read_text(encoding="utf-8") == self.index_text()

    def write_index(self) -> bool:
        self.dir.mkdir(parents=True, exist_ok=True)
        text = self.index_text()
        if self.index_path.is_file() and self.index_path.read_text(encoding="utf-8") == text:
            return False
        self.index_path.write_text(text, encoding="utf-8")
        return True


# --------------------------------------------------------------- commands

def cmd_new(reg: Registry, args: argparse.Namespace) -> int:
    severity = args.severity.lower()
    if severity not in SEVERITIES:
        raise KiError(f"--severity must be one of {', '.join(SEVERITIES)}")
    title = " ".join(args.title.split())
    if not title:
        raise KiError("--title must not be empty")
    detected = args.detected or dt.date.today().strftime("%Y-%m")
    if not DETECTED_RE.match(detected):
        raise KiError("--detected must be YYYY-MM")

    issue_id = reg.next_id()
    path = reg.dir / f"{issue_id}.md"
    if path.exists():
        raise KiError(f"{reg.rel(path)} already exists")

    meta, body, errors = parse_frontmatter(TEMPLATE.read_text(encoding="utf-8"))
    if errors:
        raise KiError(f"invalid template {TEMPLATE}: {'; '.join(errors)}")
    meta.update({
        "id": issue_id,
        "title": title,
        "severity": severity,
        "status": "open",
        "location": ", ".join(p.strip() for p in args.location.split(",") if p.strip()),
        "detected": detected,
        "resolved_ref": "",
    })
    reg.dir.mkdir(parents=True, exist_ok=True)
    Issue(path, meta, body, []).save()
    reg.write_index()
    print(f"created {reg.rel(path)}; fill in its TODO sections (index updated)")
    return 0


def cmd_resolve(reg: Registry, args: argparse.Namespace) -> int:
    issue = reg.get(args.id.upper())
    if issue.status == "resolved":
        raise KiError(f"{issue.id} is already resolved ({issue.meta.get('resolved_ref') or 'no ref'}); "
                      "edit its file to change the reference, then run index")
    issue.meta["status"] = "resolved"
    issue.meta["resolved_ref"] = " ".join(args.ref.split())
    note = args.note.strip() if args.note else ""
    if "## Resolution" not in issue.body:
        issue.body = issue.body.rstrip() + "\n\n## Resolution\n\n" + (note or "TODO: what was changed and why.") + "\n"
    elif note:
        issue.body = issue.body.rstrip() + "\n\n" + note + "\n"
    issue.save()
    reg.write_index()
    print(f"resolved {issue.id} ({issue.meta['resolved_ref']}); index updated")
    return 0


def cmd_index(reg: Registry, args: argparse.Namespace) -> int:
    for issue in reg.issues():
        for problem in validate_issue(issue):
            print(f"warning: {reg.rel(issue.path)}: {problem}", file=sys.stderr)
    if args.check:
        if reg.index_is_current():
            print(f"{reg.rel(reg.index_path)} is up to date")
            return 0
        print(f"{reg.rel(reg.index_path)} is stale; run: {CLI_HINT} index")
        return 1
    changed = reg.write_index()
    print(f"{reg.rel(reg.index_path)} {'written' if changed else 'already up to date'}")
    return 0


# ---------------------------------------------------------------- migrate

def parse_legacy(text: str) -> list[dict]:
    entries: list[dict] = []
    status: str | None = "open"
    current: dict | None = None
    in_fence = False
    for line in text.splitlines():
        if line.strip().startswith(("```", "~~~")):
            in_fence = not in_fence
        if not in_fence:
            heading = LEGACY_HEADING_RE.match(line)
            if heading and line.startswith("###"):
                current = {"number": heading.group(1), "heading": heading.group(2),
                           "status": status or "open", "lines": []}
                entries.append(current)
                continue
            section = H2_RE.match(line)
            if section:
                name = section.group(1).lower()
                status = "resolved" if "resolved" in name else ("open" if "open" in name else None)
                current = None
                continue
            if line.strip() == "---":
                continue
        if current is not None:
            current["lines"].append(line)
    return entries


def _severity_from_heading(heading: str) -> str | None:
    for emoji, severity in EMOJI_SEVERITY.items():
        if emoji in heading:
            return severity
    return None


def _strip_emoji(text: str) -> str:
    for emoji in EMOJI_SEVERITY:
        text = text.replace(emoji, "")
    return " ".join(text.split())


def _split_fields(lines: list[str]) -> tuple[list[str], list[tuple[str, str]]]:
    preamble: list[str] = []
    fields: list[tuple[str, list[str]]] = []
    for line in lines:
        match = FIELD_RE.match(line)
        if match:
            fields.append((match.group(1).strip().rstrip(":").strip(), [match.group(2)]))
        elif fields:
            fields[-1][1].append(line)
        else:
            preamble.append(line)
    result = []
    for name, value_lines in fields:
        first, rest = value_lines[0], "\n".join(value_lines[1:])
        text = (first + "\n" + textwrap.dedent(rest)).strip("\n") if rest.strip() else first
        result.append((name, text.strip()))
    return preamble, result


def _rewrite_links(text: str) -> str:
    def replace(match: re.Match) -> str:
        target = match.group(2)
        if SCHEME_RE.match(target) or target.startswith("/"):
            return match.group(0)
        path, _, anchor = target.partition("#")
        if path in ("", "known-issues.md", "./known-issues.md"):
            ki = re.match(r"ki-(\d+)", anchor, re.IGNORECASE)
            if ki:
                return match.group(1) + f"KI-{ki.group(1)}.md"
            if not path:
                return match.group(0)
            return match.group(1) + INDEX_NAME
        return match.group(1) + "../" + target
    return LINK_RE.sub(replace, text)


def _path_tokens(text: str) -> list[str]:
    tokens = re.findall(r"`([^`]+)`", text)
    return [t for t in tokens if "/" in t and " " not in t and "(" not in t]


def _residual(text: str, removed: list[str]) -> str:
    for token in removed:
        text = text.replace(f"`{token}`", "")
    return re.sub(r"[\s,.;:()\-\u2014\u2013]|\band\b", "", text)


def _has_context_beyond_date(text: str) -> bool:
    rest = MONTH_YEAR_RE.sub("", text, count=1)
    rest = re.sub(r"\b\d{4}-\d{2}\b", "", rest, count=1)
    return bool(re.search(r"[A-Za-z]", rest))


def _detected_month(text: str) -> str:
    match = MONTH_YEAR_RE.search(text)
    if match:
        return f"{match.group(2)}-{MONTHS[match.group(1).lower()]:02d}"
    iso = re.search(r"\b(\d{4})-(\d{2})\b", text)
    return f"{iso.group(1)}-{iso.group(2)}" if iso else ""


def convert_entry(entry: dict, warnings: list[str]) -> tuple[dict[str, str], str]:
    issue_id = f"KI-{entry['number']}"
    severity = _severity_from_heading(entry["heading"])
    if severity is None:
        severity = "medium"
        warnings.append(f"{issue_id}: no severity emoji in heading; defaulted to medium")
    meta = {"id": issue_id, "title": _strip_emoji(entry["heading"]), "severity": severity,
            "status": entry["status"], "location": "", "detected": "", "resolved_ref": ""}

    preamble, fields = _split_fields(entry["lines"])
    sections: list[tuple[str, str]] = []
    if "\n".join(preamble).strip():
        sections.append(("Notes", textwrap.dedent("\n".join(preamble)).strip()))

    for name, text in fields:
        key = name.lower()
        if key == "location":
            paths = _path_tokens(text)
            meta["location"] = ", ".join(paths) if paths else " ".join(text.split())
            if paths and _residual(text, paths):
                sections.append(("Location", text))
        elif key == "detected":
            month = _detected_month(text)
            meta["detected"] = month
            if not month:
                warnings.append(f"{issue_id}: could not parse a month from Detected '{text[:40]}'")
            if not month or _has_context_beyond_date(text):
                sections.append(("Detected", text))
        elif key == "resolved":
            first_line, _, other_lines = text.partition("\n")
            head = RESOLVED_SEPARATOR_RE.split(first_line, maxsplit=1)
            meta["resolved_ref"] = head[0].strip().rstrip(".:;,") or "migrated"
            rest = head[1].strip() if len(head) > 1 else ""
            resolution = "\n".join(part for part in (rest, other_lines.strip("\n")) if part)
            if resolution:
                sections.append(("Resolution", resolution))
        else:
            sections.append((name, text))

    if meta["status"] == "resolved" and not meta["resolved_ref"]:
        meta["resolved_ref"] = "migrated (no Resolved line)"
        warnings.append(f"{issue_id}: resolved without a Resolved line; resolved_ref set to placeholder")

    body = "\n\n".join(f"## {name}\n\n{_rewrite_links(text)}" for name, text in sections)
    return meta, body


def cmd_migrate(reg: Registry, args: argparse.Namespace) -> int:
    source = reg.root / args.source
    if not source.is_file():
        raise KiError(f"{args.source} not found")
    archive = reg.root / ARCHIVE_TARGET
    if archive.exists():
        raise KiError(f"{ARCHIVE_TARGET} already exists; move it away before migrating")

    entries = parse_legacy(source.read_text(encoding="utf-8", errors="replace"))
    if not entries:
        raise KiError(f"no '### KI-NNN' entries found in {args.source}")
    ids = [f"KI-{e['number']}" for e in entries]
    duplicates = sorted({i for i in ids if ids.count(i) > 1})
    if duplicates:
        raise KiError(f"duplicate ids in {args.source}: {', '.join(duplicates)}")
    conflicts = [i for i in ids if (reg.dir / f"{i}.md").exists()]
    if conflicts:
        raise KiError(f"issue files already exist: {', '.join(conflicts)}")

    warnings: list[str] = []
    converted = [convert_entry(entry, warnings) for entry in entries]

    reg.dir.mkdir(parents=True, exist_ok=True)
    for meta, body in converted:
        Issue(reg.dir / f"{meta['id']}.md", meta, body, []).save()
    reg.write_index()

    archive.parent.mkdir(parents=True, exist_ok=True)
    header = (f"> **Archived**: migrated to one file per issue. Current registry: "
              f"[known-issues/README.md](../known-issues/{INDEX_NAME}).\n\n")
    archive.write_text(header + source.read_text(encoding="utf-8"), encoding="utf-8")
    source.unlink()

    open_count = sum(1 for meta, _ in converted if meta["status"] == "open")
    print(f"migrated {len(converted)} issues ({open_count} open, {len(converted) - open_count} resolved) "
          f"into {reg.rel(reg.dir)}/")
    print(f"archived the original as {ARCHIVE_TARGET}")
    for warning in warnings:
        print(f"warning: {warning}")

    references = list(_references_to(reg.root, Path(args.source).name, [reg.dir, archive.parent]))
    if references:
        print("\nupdate these references to the old file (link issues by id, e.g. known-issues/KI-012.md):")
        for ref in references:
            print(f"  {ref}")
    return 0


def _references_to(root: Path, name: str, skip_dirs: list[Path]):
    candidates = [root / "AGENTS.md", root / "README.md", root / "CLAUDE.md",
                  root / ".github" / "copilot-instructions.md"]
    docs = root / "docs"
    if docs.is_dir():
        candidates += sorted(docs.rglob("*.md"))
    for path in candidates:
        if not path.is_file() or any(d == path.parent or d in path.parents for d in skip_dirs):
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            if name in line:
                yield f"{path.relative_to(root).as_posix()}:{number}"


# ------------------------------------------------------------------- main

def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", type=Path, default=Path("."), help="repository root (default: .)")
    common.add_argument("--dir", default=DEFAULT_DIR, help=f"registry directory (default: {DEFAULT_DIR})")

    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    sub = parser.add_subparsers(dest="command", required=True)

    new = sub.add_parser("new", parents=[common], help="create a new issue file")
    new.add_argument("--title", required=True)
    new.add_argument("--severity", required=True, help="critical | medium | low")
    new.add_argument("--location", required=True, help="repo-root-relative path(s), comma separated")
    new.add_argument("--detected", help="YYYY-MM (default: current month)")
    new.set_defaults(func=cmd_new)

    resolve = sub.add_parser("resolve", parents=[common], help="mark an issue as resolved")
    resolve.add_argument("id", help="KI-NNN")
    resolve.add_argument("--ref", required=True, help="commit, MR or PR reference")
    resolve.add_argument("--note", help="text for the Resolution section")
    resolve.set_defaults(func=cmd_resolve)

    index = sub.add_parser("index", parents=[common], help="regenerate the index")
    index.add_argument("--check", action="store_true", help="exit 1 if the index is stale, write nothing")
    index.set_defaults(func=cmd_index)

    migrate = sub.add_parser("migrate", parents=[common], help="split a single-file registry into issue files")
    migrate.add_argument("--from", dest="source", default=DEFAULT_LEGACY,
                         help=f"legacy registry file (default: {DEFAULT_LEGACY})")
    migrate.set_defaults(func=cmd_migrate)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if not args.root.is_dir():
        print(f"error: {args.root} is not a directory", file=sys.stderr)
        return 2
    try:
        return args.func(Registry(args.root, args.dir), args)
    except KiError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
